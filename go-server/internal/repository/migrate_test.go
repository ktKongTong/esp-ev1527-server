package repository

import (
	"database/sql"
	"testing"
)

// openMigrationTestDB returns an empty database that uses the same SQLite
// dialect as production. A single connection keeps the in-memory database
// alive for the whole test.
func openMigrationTestDB(t *testing.T) *sql.DB {
	t.Helper()
	db, err := sql.Open("sqlite3", ":memory:")
	if err != nil {
		t.Fatalf("open test sqlite: %v", err)
	}
	db.SetMaxOpenConns(1)
	t.Cleanup(func() {
		_ = db.Close()
	})
	return db
}

func gooseVersion(t *testing.T, db *sql.DB) int64 {
	t.Helper()
	var version int64
	if err := db.QueryRow("SELECT MAX(version_id) FROM goose_db_version").Scan(&version); err != nil {
		t.Fatalf("read goose version: %v", err)
	}
	return version
}

func TestMigrateCreatesBaselineSchema(t *testing.T) {
	db := openMigrationTestDB(t)

	if err := migrate(db); err != nil {
		t.Fatalf("migrate: %v", err)
	}

	for _, table := range []string{
		"devices", "device_tombstones", "idempotency", "goose_db_version",
	} {
		var name string
		err := db.QueryRow(
			"SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?",
			table,
		).Scan(&name)
		if err != nil {
			t.Fatalf("table %s not created: %v", table, err)
		}
	}
	if version := gooseVersion(t, db); version != 1 {
		t.Fatalf("version = %d, want 1", version)
	}
}

func TestMigrateIsIdempotent(t *testing.T) {
	db := openMigrationTestDB(t)

	if err := migrate(db); err != nil {
		t.Fatalf("first migrate: %v", err)
	}
	if err := migrate(db); err != nil {
		t.Fatalf("second migrate: %v", err)
	}
	if version := gooseVersion(t, db); version != 1 {
		t.Fatalf("version = %d, want 1", version)
	}
}

// TestMigrateAdoptsAutoMigrateSchema guards the upgrade path for databases
// created by the previous AutoMigrate startup path. The baseline migration must
// record its version without touching existing rows.
func TestMigrateAdoptsAutoMigrateSchema(t *testing.T) {
	db := openMigrationTestDB(t)

	// DDL as generated by GORM AutoMigrate before migrations were versioned.
	statements := []string{
		"CREATE TABLE `devices` (`id` text,`name` text,`location` text,`codeOn` integer,`codeOff` integer,`rfProtocol` integer,`rfLength` integer,`rfRepeat` integer,`createdAtEpochMs` integer,PRIMARY KEY (`id`))",
		"CREATE TABLE `device_tombstones` (`deviceId` text,`removedAtEpochMs` integer,PRIMARY KEY (`deviceId`))",
		"CREATE TABLE `idempotency` (`idempotencyKey` text,`deviceId` text,`action` text,`createdAtEpochMs` integer,`dispatchedAtEpochMs` integer,PRIMARY KEY (`idempotencyKey`))",
	}
	for _, statement := range statements {
		if _, err := db.Exec(statement); err != nil {
			t.Fatalf("create legacy schema: %v", err)
		}
	}
	if _, err := db.Exec(
		"INSERT INTO devices (id, name, location, codeOn, codeOff, rfProtocol, rfLength, rfRepeat, createdAtEpochMs) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
		"dev_legacy", "pump", "pond", 1714739, 1714740, 22, 24, 5, 1714739000,
	); err != nil {
		t.Fatalf("insert legacy device: %v", err)
	}

	if err := migrate(db); err != nil {
		t.Fatalf("migrate: %v", err)
	}

	var name string
	if err := db.QueryRow("SELECT name FROM devices WHERE id = ?", "dev_legacy").Scan(&name); err != nil {
		t.Fatalf("legacy device lost: %v", err)
	}
	if name != "pump" {
		t.Fatalf("name = %q, want pump", name)
	}
	if version := gooseVersion(t, db); version != 1 {
		t.Fatalf("version = %d, want 1", version)
	}
}
